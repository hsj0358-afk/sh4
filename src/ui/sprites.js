/**
 * 초상 하나를 캔버스에 찍는다.
 *
 * @param {HTMLCanvasElement} canvas
 * @param {string} id 동료 id. 없으면 실루엣만.
 * @param {object} [opt] { scale, dim }
 */
export function drawPortrait(canvas, id, { scale = 4, dim = false } = {}) {
  const form = FORMS[id] || UNKNOWN;
  const skin = SKINS[id] || ['#3a352c', '#3a352c', '#3a352c', '#3a352c', '#3a352c', '#3a352c'];

  const dpr = Math.min(window.devicePixelRatio || 1, 3);
  canvas.width = W * scale * dpr;
  canvas.height = H * scale * dpr;
  canvas.style.width = `${W * scale}px`;
  canvas.style.height = `${H * scale}px`;

  const ctx = canvas.getContext('2d');
  ctx.setTransform(dpr, 0, 0, dpr, 0, 0);
  ctx.imageSmoothingEnabled = false; // 도트는 뭉개지면 도트가 아니다
  ctx.clearRect(0, 0, W * scale, H * scale);
  ctx.globalAlpha = dim ? 0.35 : 1;

  for (let y = 0; y < H; y++) {
    const row = form[y] || '';
    for (let x = 0; x < W; x++) {
      const ch = row[x];
      if (!ch || ch === '.') continue;
      const color = skin[Number(ch) - 1];
      if (!color) continue;
      ctx.fillStyle = color;
      ctx.fillRect(x * scale, y * scale, scale, scale);
    }
  }
  ctx.globalAlpha = 1;
  return true;
}

/** 초상을 담은 요소 하나. 패널에서 쓴다. */
export function portrait(id, opt) {
  const wrap = document.createElement('span');
  wrap.className = 'portrait';
  const canvas = document.createElement('canvas');
  wrap.appendChild(canvas);
  drawPortrait(canvas, id, opt);
  return wrap;
}
